"""The ITS study's native half: generated C codecs for the security envelope, timed.

`its_security` settles the SIZE question on the oracle. Runtime and memory cannot be settled
there -- a Python encoder measures Python -- so this module compiles the two envelope modules
to C with `cgen` and drives every codec over the same four envelopes:

* the transcription (`ITS-SecuredMessage-V111`) under the V1.1.1 byte rule, COER and UPER --
  ONE C struct per envelope, three encodings of it, so a difference in cost is a difference
  of encoding rule;
* the TMSAO schema under COER (its rule-neutral instance, `SecuredMessage`) and UPER (its PER
  instance, `SecuredMessagePer`) -- each rule on the instance of the schema shaped for it.

Every codec is generated by the same compiler from the same ASN.1, so "binary" here is not a
weaker or stronger implementation than "ASN.1": it is the V1.1.1 byte rule, compiled exactly
as the ASN.1 rules are. That is the controlled comparison the 2015 study could not make --
its binary codec was hand-written and its ASN.1 codec a table-driven library.

**Parity before timing.** `parity()` must hold before `bench()` means anything: every
generated encoder writes the oracle's octets for every envelope, and every generated decoder
reads the oracle's octets back to the very value the encoder started from.

**What a timing row carries.** Each codec's encode and decode are timed in interleaved
rounds against one floor measured in the same run: `memcpy` of the encoding's own length,
the least work any encoder (write N octets) or decoder (read N octets) can do on the envelope.
A codec's ratio to that floor is what transfers between hosts; the nanoseconds do not.
"""

