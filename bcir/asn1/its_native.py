def _main(argv: list[str] | None = None) -> int:  # pragma: no cover - a developer convenience
    """`python -m bcir.asn1.its_native [DIR [CC]]`: build the harness in DIR (a new directory
    when omitted, kept so the binary can be run again) and print the study's timing and memory
    tables for this host."""
    import sys

    args = sys.argv[1:] if argv is None else argv
    tmp = args[0] if args else tempfile.mkdtemp(prefix="bcir-its-")
    os.makedirs(tmp, exist_ok=True)
    binary = build(tmp, cc=args[1] if len(args) > 1 else None)
    if binary is None:
        print("no C compiler on this host")
        return 1
    print(binary)
    rows = {(t.codec, t.envelope, t.op): t for t in bench(binary)}
    print("codec        per envelope p1 / p1cert / p2 / p3: octets, encode / decode ns (median)")
    for codec, _model, _rule in CODECS:
        cells = []
        for env in range(4):
            enc, dec = rows[(codec, env, "encode")], rows[(codec, env, "decode")]
            cells.append(f"{enc.octets:3} {enc.median_ns:6.1f} / {dec.median_ns:6.1f}")
        print(f"{codec:12} " + "   ".join(cells))
    print("codec        envelope: heap, arena octets, encode / decode stack high-water")
    for m in memory(binary):
        print(
            f"{m.codec:12} {m.envelope}: {m.heap_octets}, {m.arena_octets}, "
            f"{m.encode_stack} / {m.decode_stack}"
        )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(_main())
