#!/usr/bin/env python3
"""LOSS-ONCE's microbenchmark, generated: the trainer's loss task as the tree before has it and as the tree after has
it, each copied from its own bcir_decoder_train.c (from `typedef struct loss_job` to loss_rows' comment, its
BCIR_DT_LOSS_ONCE define with it), into one C file that times each over the same logits on one thread and compares
every adjoint and term byte for byte. usage: python3 -I mk_loss_bench.py BEFORE/bcir_decoder_train.c
AFTER/bcir_decoder_train.c OUT.c   (then: cc -std=c11 -O3 -ffp-contract=off -fno-math-errno OUT.c -lm;
./a.out ROWS VOCAB ROUNDS)"""

import sys
from pathlib import Path

START = "typedef struct loss_job {"
END = "/* The loss's g.n rows over g.v logits on the pool"


def grab(path, tag):
    s = Path(path).read_text(encoding="utf-8")
    if s.count(START) != 1 or s.count(END) != 1:
        raise SystemExit(
            f"{path}: the loss task's bounds found {s.count(START)}, {s.count(END)} times"
        )
    body = s[s.index(START) : s.index(END)]
    pre = ""
    for line in s.splitlines():
        if line.startswith("#define BCIR_DT_LOSS_ONCE "):
            pre = line + "\n"
    if pre:
        body = body.replace(pre, "")
    return pre + body.replace("loss_job", f"loss_job_{tag}").replace(
        "loss_task", f"loss_task_{tag}"
    )


HEAD = r"""/* Generated by mk_loss_bench.py: the trainer's loss task before and after, each copied from its tree's
 * source, timed over ROWS rows of VOCAB logits on one thread (the median of ROUNDS rounds, the two alternating)
 * and every adjoint and term compared byte for byte. usage: loss_bench ROWS VOCAB ROUNDS */
#define _POSIX_C_SOURCE 200809L
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#define BCIR_DT_ROW_CHUNK 16
static double now(void) { struct timespec ts; clock_gettime(CLOCK_MONOTONIC,&ts); return ts.tv_sec+ts.tv_nsec*1e-9; }
static int cmpd(const void *a,const void *b) { double x=*(const double*)a,y=*(const double*)b; return x<y?-1:x>y; }
"""
MAIN = r"""
int main(int argc,char **argv) {
  size_t n,v,i,t,tasks; int rounds,r,same; uint64_t s=88172645463325252ull;
  float *lg,*d1,*d2; uint32_t *tg; unsigned char *t1,*t2; double *a,*b;
  if (argc!=4) return 2;
  n=strtoul(argv[1],0,10); v=strtoul(argv[2],0,10); rounds=atoi(argv[3]);
  lg=malloc(n*v*4); d1=malloc(n*v*4); d2=malloc(n*v*4); tg=malloc(n*4); t1=malloc(n*8); t2=malloc(n*8);
  a=malloc(rounds*sizeof(double)); b=malloc(rounds*sizeof(double));
  if (!lg || !d1 || !d2 || !tg || !t1 || !t2 || !a || !b) return 3;
  for (i=0;i<n*v;i++) { s^=s<<13; s^=s>>7; s^=s<<17; lg[i]=(float)((double)(s>>11)/9007199254740992.0*16.0-8.0); }
  for (i=0;i<n;i++) tg[i]=(uint32_t)(i*2654435761u%v);
  {
    loss_job_before jb={n,v,lg,tg,d1,t1}; loss_job_after ja={n,v,lg,tg,d2,t2};
    tasks=(n+BCIR_DT_ROW_CHUNK-1)/BCIR_DT_ROW_CHUNK;
    for (r=-1;r<rounds;r++) {
      double x=now(),y,z;
      for (t=0;t<tasks;t++) loss_task_before(&jb,t);
      y=now();
      for (t=0;t<tasks;t++) loss_task_after(&ja,t);
      z=now();
      if (r>=0) { a[r]=y-x; b[r]=z-y; }
    }
  }
  same=!memcmp(d1,d2,n*v*4) && !memcmp(t1,t2,n*8);
  qsort(a,rounds,sizeof(double),cmpd); qsort(b,rounds,sizeof(double),cmpd);
  printf("{\"rows\":%zu,\"vocab\":%zu,\"rounds\":%d,\"before_ms\":%.4f,\"after_ms\":%.4f,\"before_ns_a_logit\":%.3f,"
         "\"after_ns_a_logit\":%.3f,\"after_over_before\":%.4f,\"bytes_equal\":%s}\n",n,v,rounds,a[rounds/2]*1e3,
         b[rounds/2]*1e3,a[rounds/2]*1e9/(n*v),b[rounds/2]*1e9/(n*v),b[rounds/2]/a[rounds/2],same ? "true" : "false");
  return !same;
}
"""
Path(sys.argv[3]).write_text(
    HEAD + grab(sys.argv[1], "before") + grab(sys.argv[2], "after") + MAIN, encoding="utf-8"
)
print("loss_bench written")
